"""Read-only historical browser checks plus explicitly synthetic UI fixtures.

No production lifespan, workers or writes. Backfill submission is exercised
against an isolated in-memory database; real network collection is covered by
the worker regression tests, not simulated here as a successful collection.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from fastapi.testclient import TestClient
from playwright.sync_api import expect, sync_playwright
from sqlalchemy import create_engine
from sqlalchemy.orm import Session
from sqlalchemy.pool import StaticPool

from app.api.selection import _run_read
from app.db.base import Base
from app.db.session import get_db
from app.main import app
from app.models.selection import SelectionCandidate, SelectionRun
from tests.selection_samples import valid_scorecard


def synthetic_run(db: Session) -> SelectionRun:
    """Fixture only: these scores were not generated by a live model."""
    scorecard = valid_scorecard()
    for row in scorecard["dimensions"]:
        row.update(dimension_name=row["dimension_code"].replace("_", " "), observed_score=60,
                   coverage=1, evidence_confidence=.8, summary="合成界面验收", method="TEST")
    scorecard.update(base_score=60, coverage=1, evidence_confidence=.8,
                     profile={"profile_name": "合成界面验收", "version": "TEST"})
    docs = [{"id": n, "source_table": "stock_news", "title": f"界面测试新闻{n}",
             "fetched_at": f"2026-10-{n + 10:02d}T08:00:00Z", "content": "合成界面测试数据"}
            for n in range(1, 8)]
    docs.append({"id": 8, "source_table": "stock_notice", "title": "界面测试公告",
                 "fetched_at": "2026-10-18T08:00:00Z", "content": "合成公告"})
    facts = [{"id": "finance:1", "fact_type": "FINANCIAL_OBSERVATION", "title": "财务实际值",
              "observed_at": "2026-10-20T08:00:00Z", "properties": {"PARENTNETPROFIT": 120000000}},
             {"id": "market:1", "fact_type": "MARKET_OBSERVATION", "title": "量价实际值",
              "observed_at": "2026-10-21T08:00:00Z", "properties": {"close_price": 12.3, "volume": 500}},
             {"id": "holder:1", "fact_type": "SHAREHOLDER_OBSERVATION", "title": "股东实际值",
              "observed_at": "2026-10-22T08:00:00Z", "properties": {"holding_pct": 12.3}}]
    specs = [("NEWS", "DOCUMENT", list(range(1, 8))), ("NOTICE", "DOCUMENT", [8]),
             ("FINANCIAL", "FACT", ["finance:1"]), ("PRICE_VOLUME", "FACT", ["market:1"]),
             ("FUND_FLOW", "FACT", []), ("COMPANY", "FACT", ["holder:1"]), ("GRAPH", "RELATION", [9])]
    dimensions = []
    for code, kind, ids in specs:
        dimensions.append({"dimension": code, "status": "SUPPORTED" if ids else "INSUFFICIENT",
            "direction": "POSITIVE" if ids else "UNKNOWN", "summary": "合成界面验收，不代表真实投资研判",
            "evidence_document_ids": ids if kind == "DOCUMENT" else [],
            "evidence_fact_ids": ids if kind == "FACT" else [], "evidence_relation_ids": ids if kind == "RELATION" else [],
            "evidence_assessments": [{"reference_type": kind, "reference_id": str(ref),
                "direction": "NEGATIVE" if ref == 1 else "POSITIVE", "score": -20 if ref == 1 else 40,
                "rationale": "合成逐条评价，用于验证正负分显示"} for ref in ids]})
    run = SelectionRun(id=900039, market="CN_A", status="PARTIAL", data_mode="REAL", analysis_mode="MODEL_PARTIAL",
        candidate_count=1, completed_at=datetime.now(timezone.utc),
        criteria_json={"analysis_contract": "MULTI_SOURCE_VALUE_CHAIN_V5"})
    db.add(run)
    db.flush()
    db.add(SelectionCandidate(run_id=run.id, market="CN_A", symbol="UI_TEST", name="合成界面验收",
        entry_price=12.3, entry_date="2026-10-27", analysis_json={"model_output_status": "SUCCESS",
            "analysis_validation_status": "PASSED", "data_gate": {"status": "READY"},
            "model": {"reasoning": "合成界面验收", "confidence": .7, "decision": "WATCH", "dimensions": dimensions},
            "scoring": scorecard}, evidence_json={"documents": docs, "facts": facts,
            "graph_paths": [{"id": 9, "predicate": "OWNS", "title": "界面关系测试"}], "missing_data": ["资金数据不足"]}))
    db.commit()
    return run


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", default="http://127.0.0.1:5173")
    parser.add_argument("--database", type=Path, default=Path("quant.db"))
    parser.add_argument("--report-dir", type=Path, default=Path("validation/selection-evidence-20261028"))
    args = parser.parse_args()
    args.report_dir.mkdir(parents=True, exist_ok=True)
    engine = create_engine(f"sqlite:///file:{args.database.resolve().as_posix()}?mode=ro&uri=true")
    isolated_engine = create_engine("sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool)
    Base.metadata.create_all(isolated_engine)
    isolated_db = Session(isolated_engine)
    fixture = synthetic_run(isolated_db)

    def readonly_db():
        with Session(engine) as db:
            yield db
            assert not db.dirty and not db.new and not db.deleted

    app.dependency_overrides[get_db] = readonly_db
    client = TestClient(app)
    errors, failures, submissions = [], [], []
    try:
        historical = client.get("/api/v1/selection/runs/39").json()
        counts = historical["criteria_json"]["result_counts"]
        assert counts["passed_count"] == 0 and counts["failed_count"] == 4
        assert all(row["analysis_json"]["publication"]["status"] == "CONCLUSION_FAILED" for row in historical["candidates"])
        for candidate in historical["candidates"]:
            for section in candidate["analysis_json"]["evidence_sections"]:
                if section["dimension"] in {"FINANCIAL", "PRICE_VOLUME", "FUND_FLOW", "COMPANY", "GRAPH"}:
                    assert all(item["source_table"] not in {"stock_news", "stock_notice"} for item in section["items"])

        def fixture_payload():
            return _run_read(isolated_db, fixture).model_dump(mode="json")

        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(channel="msedge", headless=True)
            page = browser.new_page(viewport={"width": 1440, "height": 1000})
            page.on("pageerror", lambda error: errors.append(str(error)))

            def proxy(route):
                request = route.request
                headers = {"access-control-allow-origin": "*", "content-type": "application/json"}
                if request.method == "OPTIONS":
                    route.fulfill(status=204, headers={**headers, "access-control-allow-methods": "GET, POST, OPTIONS", "access-control-allow-headers": "*"})
                    return
                path = "/api/v1/" + request.url.split("/api/v1/", 1)[1]
                if path == f"/api/v1/selection/runs/{fixture.id}" and request.method == "GET":
                    route.fulfill(status=200, headers=headers, body=json.dumps(fixture_payload(), ensure_ascii=False))
                    return
                if path == f"/api/v1/selection/runs/{fixture.id}/backfill" and request.method == "POST":
                    app.dependency_overrides[get_db] = lambda: isolated_db
                    try:
                        with patch("app.jobs.governance_runner.wake_governance_runner"):
                            response = client.post(path, content=request.post_data, headers={"content-type": "application/json"})
                        submissions.append({"status": response.status_code, "body": request.post_data})
                    finally:
                        app.dependency_overrides[get_db] = readonly_db
                elif request.method != "GET" and not path.endswith("/selection/scope-preview"):
                    failures.append({"path": path, "reason": "production write blocked"})
                    route.fulfill(status=403, headers=headers, body='{"detail":"只读验收禁止写入"}')
                    return
                else:
                    response = client.request(request.method, path, content=request.post_data, headers={"content-type": "application/json"})
                if response.status_code >= 400:
                    failures.append({"path": path, "status": response.status_code})
                if path == "/api/v1/selection/runs" and request.method == "GET":
                    body = json.dumps([fixture_payload(), *response.json()], ensure_ascii=False)
                else:
                    body = response.content
                route.fulfill(status=response.status_code, headers=headers, body=body)

            page.route("**/api/v1/**", proxy)
            page.goto(f"{args.url}/#/research/selection", wait_until="domcontentloaded")
            history = page.get_by_label("历史分析批次")
            expect(history).to_be_visible(timeout=60_000)
            history.select_option("39")
            expect(page.get_by_role("region", name="分析失败处理")).to_contain_text("待复核 0 只 · 失败 4 只 · 数据不足 0 只")
            page.screenshot(path=str(args.report_dir / "01-real-history-counts.png"), full_page=True)
            table = page.locator(".batch-table-wrap tbody")
            table.locator("tr").filter(has_text="688627").get_by_role("button", name="分析与证据").click()
            dialog = page.get_by_role("dialog", name="精智达分析与证据")
            expect(dialog).to_contain_text("结论生成失败")
            assert dialog.get_by_role("img", name="八维原始评分雷达图，缺失维度留空").count() == 0
            expect(dialog.get_by_role("button", name="确认并跟踪", exact=True)).to_be_disabled()
            page.screenshot(path=str(args.report_dir / "02-real-history-invalid-conclusion.png"), full_page=True)
            dialog.get_by_role("button", name="关闭", exact=True).click()
            history.select_option(str(fixture.id))
            table.locator("tr").filter(has_text="UI_TEST").get_by_role("button", name="分析与证据").click()
            dialog = page.get_by_role("dialog", name="合成界面验收分析与证据")
            expect(dialog.get_by_role("img", name="八维原始评分雷达图，缺失维度留空")).to_be_visible()
            news = dialog.locator('[data-dimension="NEWS"]')
            expect(news.locator(".analysis-evidence-item:visible")).to_have_count(5)
            assert news.locator(".analysis-evidence-title").first.inner_text().startswith("界面测试新闻7")
            expect(news).to_contain_text("数据获取时间：2026/10/17")
            expect(news.locator(".analysis-section-score")).to_contain_text("综合分 +1.96")
            news.locator(".analysis-evidence-more summary").click()
            expect(news.locator(".analysis-evidence-item:visible")).to_have_count(7)
            expect(news).to_contain_text("偏利空 -20.00")
            news.locator(".analysis-evidence-more summary").click()
            expect(news.locator(".analysis-evidence-item:visible")).to_have_count(5)
            expect(dialog.locator('[data-dimension="FINANCIAL"]')).to_contain_text("归母净利润（元）")
            expect(dialog.locator('[data-dimension="FINANCIAL"]')).to_contain_text("120000000")
            assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
            for width in [1440, 1280]:
                page.set_viewport_size({"width": width, "height": 1000})
                assert dialog.evaluate("node => node.scrollWidth <= node.clientWidth + 1")
            page.screenshot(path=str(args.report_dir / "03-synthetic-scored-evidence.png"), full_page=True)
            dialog.get_by_role("button", name="补齐资金进出数据", exact=True).click()
            expect(dialog.locator(".batch-dialog-feedback")).to_contain_text("已提交该股票的数据补齐", timeout=15_000)
            expect(dialog.get_by_role("progressbar", name="弹窗数据补齐进度")).to_be_visible()
            expect(dialog.get_by_role("button", name="后台任务执行中…", exact=True)).to_be_disabled()
            assert len(submissions) == 1 and submissions[0]["status"] == 202, submissions
            page.screenshot(path=str(args.report_dir / "04-isolated-backfill-feedback.png"), full_page=True)
            browser.close()
        report = {"production_database_mode": "READ_ONLY", "historical_run": 39, "counts": counts,
                  "synthetic_ui_fixture": True, "isolated_backfill_submissions": submissions,
                  "browser_errors": errors, "api_failures": failures}
        assert not errors and not failures, report
        (args.report_dir / "browser-report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        print(json.dumps(report, ensure_ascii=True))
    finally:
        client.close()
        app.dependency_overrides.pop(get_db, None)
        isolated_db.close()
        isolated_engine.dispose()
        engine.dispose()


if __name__ == "__main__":
    main()
